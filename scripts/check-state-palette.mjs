#!/usr/bin/env node
/**
 * Fail CI when the state ramp's two copies stop agreeing.
 *
 * `blocked` / `done` / `running` / `failed` exist twice on purpose, and the
 * duplication is not the kind deleting fixes. `apps/chat-ui/src/index.css`
 * authors them as `oklch()` because that is what CSS wants and because the
 * lightness is *tuned* — the comments there carry the contrast reasoning, and
 * `--state-failed` is a different value from `--destructive` for a stated
 * measurement. `packages/design/src/tokens.ts` carries the same colours as sRGB
 * hex because neither a terminal nor `RGBA.fromHex` takes `oklch()`, and
 * `apps/tui/src/theme.ts` reads them.
 *
 * So one is authored and one is derived, and nothing connected them. Both were
 * correct on 2026-09-11 — all eight convert exactly — which is precisely when a
 * guard is worth writing: after they diverge, somebody has to work out which one
 * was right.
 *
 * **Why this checks rather than generates.** The obvious fix is to generate the
 * CSS from the tokens, the way `apps/docs/src/styles/theme.css` is generated by
 * `pnpm sync:theme`. It is the wrong direction here. There the tokens are the
 * authored form; here the *stylesheet* is — the oklch components are chosen for
 * contrast and annotated with why, and hex is the lossy snapshot taken for
 * consumers that cannot read oklch. Generating the authored form out of the
 * derived one would throw away the reasoning and leave the tokens looking like
 * the source of truth they are not.
 *
 * Usage:
 *   node scripts/check-state-palette.mjs
 *   node scripts/check-state-palette.mjs --self-test
 */
import { readFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { argv, exit } from 'node:process';
import { fileURLToPath } from 'node:url';

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const STYLESHEET = join(REPO, 'apps/chat-ui/src/index.css');
const TOKENS = join(REPO, 'packages/design/src/tokens.ts');

/**
 * The roles that exist in both places.
 *
 * `danger` is deliberately absent: the design package names it, and the
 * stylesheet spells the same role `--destructive` because that is the token
 * every shadcn primitive already reads. Two names for one role is worth a note
 * rather than a rename that would touch every variant in `@felix/ui`.
 */
const ROLES = ['blocked', 'done', 'running', 'failed'];

/** oklch() → sRGB hex, which is the conversion the tokens file froze by hand. */
export function oklchToHex(L, C, H) {
  const a = C * Math.cos((H * Math.PI) / 180);
  const b = C * Math.sin((H * Math.PI) / 180);
  const l = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3;
  const m = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3;
  const s = (L - 0.0894841775 * a - 1.291485548 * b) ** 3;
  const lin = [
    4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
    -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
    -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s,
  ];
  const channel = (x) => {
    const v = Math.min(1, Math.max(0, x));
    const g = v <= 0.0031308 ? 12.92 * v : 1.055 * v ** (1 / 2.4) - 0.055;
    return Math.round(g * 255)
      .toString(16)
      .padStart(2, '0');
  };
  return `#${lin.map(channel).join('')}`;
}

/**
 * The `--state-*` declarations, split by which block they are in.
 *
 * The light values sit on bare `:root` and the dark ones inside `.dark`, so the
 * split is positional: everything before the dark block is light. Reading them
 * in order and keying by role means a role declared twice in one block is the
 * later one, which is also what the browser does.
 */
export function readStylesheet(css) {
  const darkAt = css.search(/^\s*\.dark\s*\{/m);
  const out = { light: {}, dark: {} };
  for (const m of css.matchAll(/--state-([a-z]+):\s*oklch\(([\d.]+)\s+([\d.]+)\s+([\d.]+)\)/g)) {
    const where = darkAt >= 0 && m.index > darkAt ? 'dark' : 'light';
    out[where][m[1]] = oklchToHex(Number(m[2]), Number(m[3]), Number(m[4]));
  }
  return out;
}

/** `STATE_LIGHT` / `STATE_DARK` as written, without importing TypeScript. */
export function readTokens(ts) {
  const out = { light: {}, dark: {} };
  for (const [key, name] of [
    ['light', 'STATE_LIGHT'],
    ['dark', 'STATE_DARK'],
  ]) {
    const block = ts.match(new RegExp(`${name}[^=]*=\\s*\\{([^}]*)\\}`));
    if (!block) continue;
    for (const m of block[1].matchAll(/(\w+):\s*'(#[0-9a-fA-F]{6})'/g)) {
      out[key][m[1]] = m[2].toLowerCase();
    }
  }
  return out;
}

function compare(css, tokens) {
  const problems = [];
  for (const mode of ['light', 'dark']) {
    for (const role of ROLES) {
      const a = css[mode][role];
      const b = tokens[mode][role];
      if (!a) problems.push(`index.css declares no --state-${role} in ${mode}`);
      else if (!b) problems.push(`tokens.ts names no ${role} in ${mode}`);
      else if (a !== b) {
        problems.push(
          `${mode} ${role}: index.css is ${a}, tokens.ts says ${b}\n` +
            '      The stylesheet is the authored one — fix the token, or say why it differs.',
        );
      }
    }
  }
  return problems;
}

if (argv.includes('--self-test')) {
  // A guard that cannot fail is worse than none, so prove both halves move.
  const css = readStylesheet(':root{--state-done: oklch(0.432 0.095 166.913);}');
  if (css.light.done !== '#006045') {
    console.error(`✗ self-test: converted ${css.light.done}, expected #006045`);
    exit(1);
  }
  const drifted = compare(
    { light: { done: '#006045' }, dark: {} },
    { light: { done: '#ff0000' }, dark: {} },
  );
  if (!drifted.some((p) => p.includes('done'))) {
    console.error('✗ self-test: a changed token did not fail');
    exit(1);
  }
  console.log('✓ self-test passed (oklch converts, and a changed token fails)');
}

const problems = compare(
  readStylesheet(readFileSync(STYLESHEET, 'utf8')),
  readTokens(readFileSync(TOKENS, 'utf8')),
);

if (problems.length) {
  console.error('\n  the state ramp disagrees with itself:\n');
  for (const p of problems) console.error(`    ${p}`);
  console.error(
    '\n  `apps/tui/src/theme.ts` reads the tokens and chat-ui reads the CSS, so\n' +
      '  the two clients would show different colours for the same state.\n',
  );
  exit(1);
}

console.log(`✓ the state ramp agrees: ${ROLES.length} roles × 2 modes, oklch → hex exact`);
